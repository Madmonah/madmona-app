const block = src.match(/const EMOJI: \[RegExp, string\]\[\] = \[([\s\S]*?)\n\]/)[1]
const pairs = [...block.matchAll(/\[\/(.+?)\/, '(.+?)'\]/g)].map((m) => [new RegExp(m[1]), m[2]])
const norm = (s) => s.toLowerCase()
  .replace(/[\u0623\u0625\u0622]/g, 'ا').replace(/\u0629/g, 'ه').replace(/\u0649/g, 'ي')
  .replace(/[\u064B-\u0652\u0640]/g, '').replace(/\s+/g, ' ').trim()
const emoji = (n) => { const x = norm(n); const f = pairs.find(([re]) => re.test(x)); return f ? f[1] : '🍽️' }

