-- ٢١ أغسطس ٢٠٢٦ — هوية البيزنس بقت ديناميك
-- ============================================================================
-- محمد: «خليني أقدر أعدّل الكلام ده ديناميك، ومن هنا ورايح اللي تقدر تخليه
--        ديناميك خليه ديناميك»
--
-- «الكلام ده» = اللي عدّلته بالإيد في SQL وأنا بعمل بيزنس ستار أليكس:
--   اللوجو · الغلاف · وصف النشاط · معرض الصور · الألوان
-- دلوقتي كله من تاب «الهوية» جوّه إعدادات البيزنس.
--
-- ========================== باج اتكشف وإحنا بنبني ===========================
-- 🐞 **صاحب البيزنس ماكانش يقدر يحفظ أي حاجة في إعداداته.**
--    البوليسي الوحيدة على `suppliers` للـ`authenticated` هي
--    `suppliers_admin_only` = `is_admin()`. وتاب «الأساسية» بينادي
--    `supabase.from('suppliers').update(...)` من المتصفح على طول —
--    يعني أي حد غير أدمن المنصة كان بيدوس «احفظ»، ماتغيّرش ولا صف،
--    و**مفيش أي رسالة خطأ**. RLS بترجّع 0 rows مش error.
--    عشان كده الهوية بتتحفظ من RPC مش من الجدول على طول.
--
-- ============================== اللي اتعمل =================================
--   1) business_can_edit_identity(supplier)
--        أدمن المنصة · موظفين مضمونة · صاحب البيزنس (my_supplier_access.full)
--        ⚠️ مش بتستخدم `erp_is_privileged` عن قصد — دي بتشترط اشتراك شغّال،
--           والهوية مش ميزة مدفوعة، ومحمد قال «لسه محدش دفع اشتراك».
--
--   2) business_identity_get(supplier)
--        بترجّع الهوية + **مكتبة صور البيزنس نفسه** (صور إعلاناته، من غير
--        صور الأقسام العامة) عشان يختار اللوجو/الغلاف بدوسة بدل ما يرفع تاني.
--        ستار أليكس مثلًا بترجّعله ٢٤ صورة.
--
--   3) business_identity_save(supplier, logo, cover, description, gallery, accent, theme_on)
--        • بتبني الثيم من **لون واحد** بدل ما الواجهة تكتب jsonb خام —
--          فشكل الثيم يفضل صح، ولو زوّدنا مفتاح جديد يتزوّد في مكان واحد
--        • بترفض أي لون مش بصيغة #RRGGBB
--        • بترمي أي صورة في المعرض من غير url
--        • بتحدّث `marketplace_suppliers.logo_url` كمان — الماركتبليس بيقرا
--          اللوجو من الجدول ده، وده اللي كان بيخلّي نفس الشركة تبان صح في
--          مكان وغلط في مكان تاني
--        • `theme_on=false` → بتمسح الثيم فالبيزنس يرجع لهوية مضمونة
--
--   4) الواجهة: `src/components/business/IdentityTab.tsx`
--        تاب «الهوية» في إعدادات البيزنس — معاينة حيّة للهيدر زي ما العميل
--        هيشوفه، منتقي من صور البيزنس، رفع صورة، ٨ ألوان جاهزة + منتقي لون.
--
-- ================================ متأكد منه ================================
--   anon                     → forbidden على get و save
--   محمد                     → get شغّال، ٢٤ صورة راجعة
--   لون «أزرق» (مش hex)      → اترفض برسالة عربية
--   صورة معرض من غير url     → اترمت (٢ داخلين → ١ متسجّل)
--   (كله في transaction اترجعت)
--
-- ============================ اللي لسه ثابت في الكود ========================
-- للعِلم لما نكمّل «اللي ينفع يبقى ديناميك»:
--   • نصوص كل نشاط في `/s/[slug]` (`VERTICALS`) — «احجز رحلتك» / «من على
--     المركب» / «مكان الانطلاق» … لسه متكتبة في الكود لكل نشاط
--   • `THEME_BY_SLUG` — ماب قديم بالـslug، بقى مالوش لازمة بعد ما الثيم
--     بقى في الداتابيز
--   • مكتبة لوجوهات المطوّرين في `public/developers/` — ملفات في الريبو
