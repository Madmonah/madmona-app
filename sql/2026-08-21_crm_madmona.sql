-- ============================== الأرقام اللي عندنا =========================
--   ٣٬٠٨٤ رقم في `whatsapp_conversations`
--   ٢٬٣٧١ رقم مصري صالح بعد التطبيع  → دول اللي دخلوا `crm_contacts`
--         (الباقي إما مكرّر، أو مش رقم أصلًا — زي IDs الواتساب
--          `274625208541390` اللي `crm_norm_phone` بترجّعلها NULL)
--
--   مصادر الأرقام: whatsapp_conversations + suppliers + customers + listings
--   التقسيم: ١٬٩١٤ ليد · ٢٩٣ عميل · ١٦٤ بيزنس
--
-- ============================== الجداول ====================================
--   `crm_specialties`       التخصصات + قواعد المطابقة (١١ تخصص)
--   `crm_staff_specialties` مين مسؤول عن إيه   (profile_id, specialty)
--   `crm_contacts`          الأرقام + التخصص + المسؤول + الحالة
--   `crm_calls`             المكالمات المفرّغة (transcript · summary · outcome)
--   `flow_tasks`            +٧ أعمدة: owner_id · contact_id · call_id ·
--                           specialty · due_at · routed_from · route_reason
--
--   ⚠️ عملنا `flow_tasks` أوسع بدل ما نعمل جدول تاسكات تاني — عشان تاسكات
--      مضمونة تفضل في مكان واحد، والتاسك اللي جاي من مكالمة بيتعرف بـ
--      `source='crm-call'`.
--
-- ============================== الدوال =====================================
--   crm_norm_phone(text)              ٠١XXXXXXXXX أو NULL لو مش رقم
--   crm_norm_ar(text)                 تطبيع عربي (أإآ→ا · ة→ه · ى→ي · تشكيل)
--   crm_specialty_for_cat(slug)       سلَج تصنيف → تخصص (احتواء مش تساوي)
--   crm_specialty_for_text(text)      نص → تخصص بالتصويت على الكلمات
--   crm_staff()                       موظفين مضمونة **اللي عندهم حساب**
--   crm_pick_owner(specialty)         أقل واحد حِمل في التخصص ده
--   crm_ingest_contacts()             جمع الأرقام من كل مكان (idempotent)
--   crm_classify_contacts(force)      تصنيف بسلّم أولويات
--   crm_assign_round_robin(spec,re)   التوزيع بالدور جوّه كل تخصص
--   crm_log_call(...)                 تفريغ مكالمة + توليد التاسكات + التحويل
--   crm_task_update(...)              تعديل/إقفال تاسك (وإعادة توجيه)
--   crm_overview() · crm_contacts_list() · crm_contact_detail() · crm_tasks_list()
--   crm_save_specialty() · crm_set_staff_specialties() · crm_set_contact()
--
-- ========================= سلّم التصنيف (الأقوى الأول) ======================
--   1) supplier     تصنيف إعلانات البيزنس نفسه        ٤٤٨ رقم
--   2) wa_category  `whatsapp_conversations.first_category`  ١٩٦ رقم
--   3) listing      إعلان مسجّل بنفس الرقم              ٢ رقم
--   4) words        كلمات في رسايله الواردة             ٢٤٣ رقم
--   5) none         **بيفضل فاضي** — مابنخمّنش        ١٬٤٨٢ رقم
--
--   المحصلة: ٨٨٩ متصنّف · ١٬٤٨٢ لأ.
--
--   ⚠️ ليه ١٬٤٨٢ لسه مش متصنّفين؟ لأن **١٬٤٦٤ منهم مبعتوش ولا رسالة واردة**
--      خالص (دول أرقام إحنا بعتنالهم في كامبين أو أرقام عملاء متسجّلة عند
--      بيزنس من غير محادثة). مفيش عليهم أي دليل — والصح إننا نقول كده
--      صراحةً مش نحطّهم في خانة عشوائية. بيبانوا في الشاشة تحت
--      «لسه مش متصنّف» وبيتوزّعوا على الفريق كله عشان حد يكلّمهم.
--
-- ⚠️ **إعادة التصنيف مابتدهسش التصنيف اليدوي.** أي رقم اتظبط من الشاشة
--    بيتسجّل `specialty_src='manual'` وبيتساب في حاله.
--
-- ============================== التخصصات ===================================
--   عقارات ٢٥٨ · تجميل وسبا ٣٠٧ · مطاعم وكافيهات ١٢٠ · عربيات ٧٠ ·
--   طبي وعيادات ٥٤ · متاجر ومنتجات ٢١ · سياحة وترفيه ١٩ · توظيف ١٨ ·
--   خدمات ومهنيين ١٣ · يخوت ومراكب ٩ · متنوّع ٠
--
--   🔍 «توظيف» اتضاف لما قريت الرسايل اللي مامطبقتش: فيه ناس بتكلّم مضمونة
--      تسأل على شغل («بستفسر على الشغل المتاح» · «معفى من الجيش خريج آداب»)
--      — دي مش ليد مبيعات وماكانش لها مكان.
--   🔍 والكلمات الإنجليزية اتضافت لأن نصّ كبير من الردود الأوتوماتيك اللي
--      البيزنسات بتبعتها إنجليزي (`clinic` · `real estate` · `makeup`).
--
-- ========================= التوجيه التلقائي (اللي محمد طلبه) ================
--   في `crm_log_call`، كل تاسك ممكن يجيله `specialty` خاص بيه:
--     • التخصص = تخصص العميل            → التاسك يفضل مع اللي عمل المكالمة
--     • التخصص مختلف وليه مسؤول         → **بينزل عند المسؤول أوتوماتيك**،
--       و`routed_from` + `route_reason` بيتكتبوا فيفضل واضح مين حوّله وليه
--     • التخصص مختلف ومالوش مسؤول       → بيفضل مع صاحب المكالمة **والسبب
--       مكتوب**: «التخصص «marine» لسه مالوش مسؤول»
--
--   ✅ متأكد منه بتجربة اترجعت (سامية=عقارات · شهد=عربيات):
--        مكالمة عن شقة + العميل قال عنده عربية للبيع →
--          «ابعتله ٣ شقق في سموحة»            → فضل مع سامية
--          «كلّمه على عرض العربية المستعملة»  → **نزل عند شهد تلقائيًا**
--          تاسك على تخصص «marine» ملوش مسؤول  → فضل مع سامية والسبب مكتوب
--
-- ============================== الأمان =====================================
--   كل الـRPCs محميّة بـ`is_madmona_staff() OR is_admin_or_service()`.
--   الجداول الأربعة عليها RLS **قراءة بس** لموظفين مضمونة والأدمن —
--   وكل كتابة بتعدّي من RPC. (`crm_*_read_staff` policies)
--
--   ⚠️ الجداول كانت متعمولة بـRLS من غير أي policy = صفر صلاحية لأي حد
--      غير الـservice role. الكتابة سايبينها كده عن قصد.
--
-- ============================= اللي لسه محتاج قرار منك =====================
--   1) 🔴 **مين مسؤول عن كل تخصص** — دي أول خطوة في الشاشة. من غيرها
--      التوزيع بيتعمل على الفريق كله بالتساوي (٤٧٠ رقم لكل واحد تقريبًا).
--   2) ٣ موظفين في `business_employees` **مالهمش حساب على المنصة** فمينفعش
--      يتوزّع عليهم: إيمان محمد أحمد · محمد عبدالجابر · مديحة عبدالفتاح.
--   3) ١٬٤٦٤ رقم مبعتش ولا رسالة — محتاجين مكالمة عشان نعرف هم إيه.
--
-- ============================= اللي لسه مش متعمل ============================
