-- ٢١ أغسطس ٢٠٢٦ — أي خدمة أو منتج لأي بيزنس بقى يبان في الماركتبليس
-- ============================================================================
-- محمد: «عايز أي منتج أو خدمة أو مشروع أو أي نشاط لأي بيزنس يسمع في
--        الماركت بليس»
--
-- ============================== المشكلة ====================================
-- الماركتبليس بيقرا من جدول واحد: `listings`. لكن شغل البيزنس الحقيقي
-- متوزّع على تلات أماكن:
--
--   `listings`               ٣٩١ منشور     → في الماركتبليس ✅
--   `services_catalog`       ٢٠٦ خدمة نشطة → **مش في الماركتبليس** ❌
--   `inventory_products`     ٣٥ منتج retail→ **مش في الماركتبليس** ❌
--   `property_market_items`  ١٦٩ مشروع     → بيتزنقوا أصلًا بـsync_bourse_to_ads ✅
--
-- يعني منيو ٩ مطاعم، و**٤٧ خدمة في Elite Beauty Salon**، و١٠ خدمات في
-- سعداوي جراج — كلهم مخفيين تمامًا عن أي عميل بيدوّر في الماركتبليس.
--
-- 🔍 وده كمان بيقفل قصة «الوقفة الجماعية» بتاعة ١٨ أغسطس نهائي:
--    الـ١٢٥ صنف منيو اللي اتوقفوا في نفس الدقيقة **اتنقلوا من `listings`
--    لـ`services_catalog`** — نفس المطاعم بالظبط (رقاق المدق ٤١ خدمة ·
--    سوق السمك ١٩ · Rino's ١٦ · دنيا الجمبري ١٢ · HEROS ١٠ · مشوي ومندي ٩
--    · مطاعم شعبان ٧ · سناب جريل ٦ · قصر المندي ٢ · حاتي المجنون ٢).
--    فالوقفة كانت مقصودة زي ما استنتجت — بس نتيجتها إن المنيو **اختفى**.
--
-- ============================== الحل =======================================
-- **إسقاط (projection) مش نسخ يدوي.** الصف في `listings` بيتولّد من المصدر
-- ويفضل مربوط بيه بـ(`source_kind`,`source_ref`)، فأي تعديل في المصدر
-- بيتحدّث في الماركتبليس لوحده.
--
-- ليه مش union في استعلام الماركتبليس؟ لأن الشاشة دي بتعمل فلترة على شجرة
-- التصنيفات والـtrack والبحث والمورّد والعقارات (بريمري/ريسيل/مفروش) —
-- تحويلها لـunion كان يعني إعادة كتابة أهم شاشة للعميل. الإسقاط بيدي نفس
-- النتيجة من غير ما نلمس سطر واحد في الماركتبليس.
--
--   1) listings.source_kind + source_ref  (+ unique index)
--   2) project_offer_to_listing(kind, ref)
--   3) trg_project_service على `services_catalog`
--      trg_project_product على `inventory_products`  (INSERT/UPDATE/DELETE)
--   4) حصر لكل اللي موجود
--
-- ========================== قرارات مهمة في التنفيذ ==========================
-- ⚠️ **بنتبنّى الإعلان القديم بدل ما نعمل جديد.** لو فيه إعلان بنفس الاسم
--    عند نفس البيزنس (الـ١٢٥ الموقوفين)، بنربطه بالخدمة — كده **صوره
--    الحقيقية بتفضل معاه** بدل ما نخلق إعلان فاضي جنبه. ١٣ إعلان رجعوا
--    منشورين على طول بصورهم بالطريقة دي.
--
-- ⚠️ **الحالة `published` بس لو معاه صورة حقيقية + سعر.** غير كده `draft`،
--    ويبان في شاشة «الإعلانات الواقفة» بـ«ناقص صور حقيقية». دي قاعدة محمد
--    نفسه: «أي خدمة/منتج/منيو يتعرض لازم بسعر وصورة».
--
-- ⚠️ **مابنلفّش حوالين حارس النشر.** فيه
--    `enforce_listing_publish_requirements` بيطلب رقم موثّق بالواتساب.
--    لو رفض، الإعلان بيتسجّل `draft` والسبب بيتكتب في `pause_reason`.
--    (١٦ إعلان وقعوا في الحارس ده في التجربة.)
--
-- ⚠️ **`operational` مش بيبان.** `inventory_products.product_type` بيفرّق
--    بين مخزون داخلي (بُن · لبن · بوجيه · منظف = ٢١٨ صنف) ومنتجات للبيع
--    (`retail` = ٣٥). الداخلي مايدخلش الماركتبليس.
--
-- ⚠️ **مضمونة متستثناة** — ٧ خدمات عندها اتخطّوا، عشان
--    `trg_block_listings_on_platform_owner`.
--
-- ============================== النتيجة ====================================
--   ٢٢٤ إعلان مشتق (١٨٩ من الخدمات · ٣٥ من المنتجات)
--   ١٣ اتنشروا على طول بصورهم           → الماركتبليس ٣٩١ → ٤٠٤
--   ١٧٦ درافت مستنيين صور               → بيبانوا في شاشة «الإعلانات الواقفة»
--   ١٠ اتخطّوا: `no_category` (سعداوي جراج مالوش أي تصنيف على أي إعلان)
--   ٧ اتخطّوا: مضمونة
--
-- ============================== متأكد منه ==================================
--   تعديل سعر خدمة   → الإعلان اتحدّث (٩٩٩٩) ✅
--   خدمة جديدة       → إعلان جديد اتعمل درافت ✅
--   إقفال الخدمة     → الإعلان اتوقف بسبب مكتوب ✅
--   خدمة بصور        → اتبنّت الإعلان القديم ونشرت بصوره ✅
--   (كله في transactions اترجعت، وبعدين الحصر اتنفّذ)
--
-- باك أب: `_backup_listings_before_projection_20260821`
--
-- ============================== لسه ناقص ===================================
--   • `public_salon_landing` بيعدّ نفس الصنف مرتين دلوقتي (مرة في
--     `service_count` ومرة في `product_count`) — محتاجة توحيد
--   • سعداوي جراج محتاج تصنيف على إعلاناته عشان الـ١٠ خدمات بتوعه يبانوا
-- ============================================================================

ALTER TABLE listings
  ADD COLUMN IF NOT EXISTS source_kind text,
  ADD COLUMN IF NOT EXISTS source_ref uuid;

CREATE UNIQUE INDEX IF NOT EXISTS listings_source_uniq
  ON listings (source_kind, source_ref) WHERE source_kind IS NOT NULL;

