-- محمد: «الإعلانات اللي في المسودة عايز أعرف مشكلتها إيه، والإعلانات
--        الموقوفة برضو عايز أعرف اتوقفت ليه»
--
-- ======================== اللي اتلقى في الداتا ===============================
-- **١٩٣ إعلان موقوف — وولا واحد فيهم عليه سبب مكتوب.**
-- السبب: مكانش فيه خانة سبب إيقاف في الجدول أصلًا. (فيه
-- `publish_exception_reason` بس دي بتتكتب من `expire_publish_exceptions`
-- لوحدها، ومستخدمة على إعلان **واحد** من الـ١٩٣.)
--
-- ولما بصّينا على وقت الإيقاف طلع إن الوقفات **جماعية** مش فردية:
--
--   ١٢٥ إعلان  ·  ١٨/٠٨ ١٢:٤١ ص  ·  في نفس الدقيقة
--       كلهم أصناف منيو لـ١١ مطعم، وكل مطعم فضل ليه **إعلان واحد منشور**
--       (المطعم نفسه). يعني وقفة مقصودة لتجميع المنيو جوّه إعلان المطعم:
--         رقاق المدق 39 موقوف / 3 منشور · سوق السمك 19/1 · Rino's 16/1 ·
--         دنيا الجمبري 12/1 · HEROS 10/1 · مشوي ومندي 9/1 · سناب جريل 8/1 ·
--         مطاعم شعبان 7/1 · قصر المندي 2/1 · حاتي المجنون 2/0 · Abo Shady 1/1
--       ⚠️ «حاتي المجنون» فضل بصفر إعلان منشور — إعلان المطعم بتاعه لسه
--          درافت وناقصه صور. يعني المطعم ده اختفى من المنصة بالكامل.
--       ⚠️ الـ١٢٥ دول **مالهمش أي نقص بيانات** — صور وأسعار وتصنيفات تمام.
--          فالوقفة كانت قرار، مش عيب في الإعلان. وده الفرق اللي الشاشة
--          الجديدة بتوضّحه.
--
--    ٢٥ إعلان  ·  ٣٠/٠٧ ١٠:٥٨ ص
--       كلهم من دليل المطاعم والكافيهات، و**كلهم** من غير سعر ومن غير رقم موثّق.
--
--    ١٧ إعلان  ·  ١٤/٠٨ ٠٧:٣٤ ص
--       ١٦ من الـ١٧ من غير سعر.
--
--    ٢٦ إعلان  ·  متفرقين — مفيش أي نمط يفسّرهم.
--
-- ⚠️ مفيش `audit_log` للفترات دي، فمحدش يقدر يقول **مين** عملها. الأسباب
--    اللي اتكتبت على الـ١٦٧ الأولانيين **استنتاج من الداتا ومكتوب فيهم كده
--    بالنص**، والـ٢٦ الباقيين اتكتبلهم «السبب مش مسجّل — محتاج مراجعة».
--    مااخترعناش سبب مانعرفهوش.
--
-- ============================== اللي اتعمل ==================================
--   1) listings.pause_reason / paused_at / paused_by
--   2) admin_bulk_set_status: `paused` من غير سبب = **رفض العملية**
--      (زي `rejected` بالظبط اللي اتعمل الصبح)
--   3) admin_stalled_listings(status): كل إعلان واقف — درافت أو موقوف أو
--      مرفوض — وجنبه:
--        • السبب المسجّل
--        • **ناقصه إيه دلوقتي** (محسوب من الداتا الحالية، مش تخمين للماضي)
--        • `batch_size` = كام إعلان اتوقف في نفس الدقيقة → ده اللي كشف
--          الوقفات الجماعية
--   4) admin_publish_listing بقت تقبل `paused` كمان (رجّع الموقوف)، وبتفضّي
--      pause_reason لما الإعلان يرجع. المرفوض **مش** من هنا عن قصد.
--   5) admin_listings_search بيرجّع السببين وتواريخهم
--   6) الواجهة: مودال واحد بيطلب السبب للرفض والإيقاف، والسبب بيبان
--      في /admin/listings و/admin/drafts **ولصاحب البيزنس في شاشته**
--
-- باك أب: `_backup_paused_reasons_20260821`
-- ============================================================================

ALTER TABLE listings
  ADD COLUMN IF NOT EXISTS pause_reason text,
  ADD COLUMN IF NOT EXISTS paused_at timestamptz,
  ADD COLUMN IF NOT EXISTS paused_by uuid REFERENCES profiles(id) ON DELETE SET NULL;

