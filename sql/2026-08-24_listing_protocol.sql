-- ============================================================================
-- ٢٤ أغسطس ٢٠٢٦ — بروتوكول تسجيل الإعلان (مقفول)
-- ============================================================================
-- محمد:
--   «فلان من مضمونة سجل اعلانك واكتب تفاصيل الاعلان واطلب منه صور ولما يبعت
--    الصور الاعلان ينزل باسمه وصورته بس فعلا يكون الداتا بتاعت الاعلان محفوظة
--    عندنا — اقفل البروتوكول بتاع الشغل دلوقتي ومش عايز اي غلط»
--
-- ============================== البروتوكول ==================================
--   ١) الموظف بيسجّل الإعلان من تاب «إضافة» في /crm — **من غير صور**
--   ٢) العميل بيستلم: «فلان من مضمونة سجّل إعلانك» + تفاصيل الإعلان + طلب الصور
--   ٣) العميل بيبعت الصور على واتساب
--   ٤) الصور بتتلزق على الإعلان **في الكود مش بأداة للمارد**
--   ٥) الإعلان بينزل باسم صاحب الرقم وبصوره
--   ٦) المارد بيقرا اللي حصل ويقوله — مابيوعدش ومابيتوقّعش
--
-- ============================ الأعطال اللي اتقفلت ===========================
-- 🐞 (١) **رسالة اتبعتت ٣ مرات لنفس الرقم.** الراوت كان بيحط رسالة في الطابور
--        مع كل PATCH فيه status='submitted'، والويزارد بيبعت أكتر من واحد.
--        دلوقتي `listing_notify_submitted` بتشوف الطابور قبل ما تكتب.
--
-- 🐞 (٢) **الرسالة كانت بتقول «استلمنا منتجك» لناس مبعتوش حاجة.** لما الموظف
--        هو اللي سجّل، العميل بيستلم رسالة عن حاجة معملهاش. دلوقتي فيه نص
--        مستقل لكل حالة في `listing_confirm_templates`.
--
-- 🐞 (٣) **الإعلان كان بينزل باسم الموظف.** `MadmonaListingClaimer` في اللاي
--        أوت بيراقب `?token=` في أي صفحة وبيستلم المسودة لأي حد مسجّل دخول.
--        يوم ٢٤ أغسطس مسودة رقمها +٢٠١١٥٦٦٣٠٧٤٤ راحت باسم شهد.
--        دلوقتي `tg_lock_draft_owner` بترفض أي استلام من رقم مختلف.
--
-- 🐞 (٤) **الويزارد كان بيقفل على صفر صور**، فالسيناريو اللي محمد طلبه كان
--        مستحيل من الأساس — الموظف في التليفون ومامعاهوش صور العميل.
--        دلوقتي `utm_source=crm` بس هي اللي بتعدّي من غير صور.
--
-- ============================== ليه في الداتابيز ============================
--   الرسالة بتتبني من **صف المسودة نفسه**. يعني لو الداتا مش محفوظة، الرسالة
--   أصلًا مش هتتكتب. مفيش طريقة نبعت «سجّلنا إعلانك» وإحنا مش سجّلنا حاجة.
--   ده الرد المباشر على «بس فعلا يكون الداتا بتاعت الاعلان محفوظة عندنا».
--
--   وبنفس المنطق: لزق الصور بيحصل في **مسار الواتساب مباشرة**، مش بأداة
--   للمارد. درس ١٨ و١٩ أغسطس: أي حاجة لازم تحصل فعلًا مايصحّش تكون معلّقة
--   على إن النموذج «يفتكر» ينادي أداة.
--
-- ⚠️ وفايدة تانية مقصودة: حارس التجميع في مسار الواتساب بيرمي كل صورة غير
--    الأخيرة **قبل** ما توصل للنموذج. لو اللزق كان بأداة، العميل اللي بيبعت
--    ١٩ صورة كانت هتتحفظ منهم واحدة. دلوقتي كلهم بيعدّوا على `listing_attach_photos`.
--
-- ============================== اللي اتأكد بتجربة ===========================
--   مسار (ب) — رقم له بروفايل (الإعلان بيتحوّل فورًا لـpending_review بصفر صور):
--     notify   → صف واحد في الطابور · staff='عبير ايهاب' · awaiting_photos=true
--     نداء تاني → already_sent (مفيش تكرار)
--     صورتين   → الإعلان **اتنشر**، صاحبه «Ahelh Elalfy» (العميل مش الموظف)،
--                ٢ صورة، صورة رئيسية واحدة
--     صورة تالتة بعد النشر → 'no draft awaiting photos' (مفيش شغل مكرر)
--   مسار (أ) — رقم من غير بروفايل: الصور اتحفظت، والنشر اترفض بـ
--     «phone must be verified via WhatsApp OTP or have an inbound WhatsApp message»
--     — والشرط ده **بيتحقق لوحده** في الواقع لأن العميل لسه باعت الصور على
--     واتساب، والرسالة الواردة بتتسجّل قبل اللزق.
--   القفل: محاولة استلام مسودة عميل باسم شهد → اترفضت، claimed_by فضل null.
--   كل صفوف التجربة اتشالت — الداتابيز نضيفة.
-- ============================================================================

-- ملاحظة: نصوص الرسايل والدوال الكاملة موجودة في الداتابيز.
-- لإعادة البناء من الصفر شغّل `node scripts/dump-crm-sql.mjs` وخد النسخة الحيّة.

-- ─────────────────────── الجدول: نصوص الرسايل ───────────────────────
create table if not exists public.listing_confirm_templates (
  key        text primary key,
  label_ar   text,
  body_ar    text not null,
  active     boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by uuid
);
alter table public.listing_confirm_templates enable row level security;
drop policy if exists listing_confirm_templates_read on public.listing_confirm_templates;
create policy listing_confirm_templates_read on public.listing_confirm_templates
  for select using (public.is_madmona_staff() or public.is_admin_or_service());

