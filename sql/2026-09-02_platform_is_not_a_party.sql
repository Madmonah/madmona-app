-- 🏛️ (٢ سبتمبر ٢٠٢٦) محمد: «مضمونة معندهاش اعلانات».
--
-- ═══ اللي كان بيحصل ═══
-- الموظف بيضيف إعلان بالنيابة عن عميل (شقة · عربية · شاليه)، ومفيش حساب
-- مورد للعميل، فالإعلان بيقع على حساب المنصة `267e0655-…` («مضمونة»).
-- وصفحة الإعلان بتعرض كارت:
--     «صاحب الإعلان: مضمونة ✅ مورد موثّق»
-- يعني المنصة بتبان **بايعة** شقة وعربية بتاعت ناس. ده كسر مباشر لهوية
-- المشروع: مضمونة **وسيط ضامن في النص، مش طرف** — «عن طريق مضمونة»
-- مش «من مضمونة».
--
-- ٢٢ إعلان منشور كانوا كده (كلهم عقارات ومركبات).
--
-- ═══ العلاج ═══
-- علامة صريحة على حساب المنصة بدل ما كل شاشة تقارن بالاسم:
--   `marketplace_suppliers.is_platform`
-- والصفحة بتعرض «معروض عن طريق مضمونة — وسيط ضامن» بدل كارت المالك.
--
-- ⛔ **وممنوع نعرض اسم المالك الحقيقي مكانه** — قاعدة ٢٧/٨: الاسم والرقم
--    مايبانوش إلا بعد الاتفاق في حضور مضمونة (partyPhoneHidden سارية على
--    sale-properties · sale-vehicles · sale-tourism، وهي بالظبط أقسام
--    الـ٢٢ إعلان دول).
--
-- ⚠️ **الـGRANT على مستوى العمود** — درس ٢/٩ (seller_display_name):
--    صلاحيات anon على الجداول دي ممنوحة **عمود بعمود**، و PostgREST
--    بيرفض **الاستعلام كله** لو فيه عمود واحد مش مسموح. وعمود من غير
--    grant بيوقّع الشاشة كلها مش الصفوف اللي عليه بس.
--
-- 📌 ملاحظة اتسجّلت للمراجعة (مش اتغيّرت): الـ٢٢ إعلان كل واحد فيهم ليه
--    `contact_phone` و/أو `owner_name` للمالك الحقيقي — بس **مش** كلهم
--    صالحين لعمل حسابات موردين: بعض الأرقام أرقام **موظفين** (شهد ·
--    عبير) اتحطّت كرقم تواصل مش كملكية. فالإسناد الحقيقي محتاج قرار
--    محمد حالة بحالة — العرض اتصلح، والملكية اتساب زي ما هي.

alter table public.marketplace_suppliers
  add column if not exists is_platform boolean not null default false;

update marketplace_suppliers set is_platform = true
where id in ('267e0655-96d9-431e-bf12-b4c2cd58778a',   -- عليه الـ٢٢ إعلان
             'c8b7b9d7-6178-4d0c-abdf-66f34b628e9d');  -- MADMONA (فاضي)

grant select (is_platform) on public.marketplace_suppliers to anon, authenticated;

