-- ═══ المبدأ ═══
-- كل واحد ياخد اللي شغله محتاجه بالظبط — لا أكتر ولا أقل.
--
--   مبيعات  : إعلانات (إضافة · نشر · حذف) + عملاء + حجوزات + خدمات
--             + تقييمات + تحليلات
--   دعم فني : زي المبيعات + المخزون (السيارات ليها مخزون)
--   أوفيس   : يعدّل الإعلانات ويرفع صور — **مش بينشر ولا بيحذف**
--
-- ⛔ الفلوس والتسعير (can_view_finance · can_manage_pricing ·
--    can_view_reports · can_add_expense) = false لكل اللي مش owner.
--    ده صحّح **انحراف كان موجود فعلًا** وكشفه الفحص:
--      إيمان  كان عندها can_view_finance = true
--      مديحة كان عندها can_view_finance + can_manage_pricing = true
--    بالمخالفة للقاعدة المكتوبة («ما عدا الفلوس والتسعير لحد أمر صريح»).
--
-- ⛔ إدارة الفريق والفروع والموظفين = للـowner بس — مش دور مبيعات.
--    (ده بيلغي فتح can_manage_team اللي اتعمل قبلها بساعة لنورا وعبير
--     وشهد — الطلب اتغيّر لـ«حسب الدور»، وإدارة الفريق مش دور مبيعات.)
