-- ═══ الأدوار الفعلية (من role_ar + metadata->team) ═══
--   الإدارة  · محمد ناصف       — صاحب المنصة            → all
--   إشراف    · أحمد سامي       — مدير فرع                → all
--   مبيعات   · مديحة           — مسؤولة المكالمات
--   مبيعات   · عبير · شهد      — مسؤولات العقارات
--   دعم فني  · إيمان           — مسؤولة السيارات
--   أوفيس    · محمد عبدالجابر  — مسؤول التصوير والمحتوى
