-- 🏬 (٢ سبتمبر ٢٠٢٦) محمد: «اربط الإعلانات الصيدلانية بمورديها الحقيقيين».
--
-- ═══ المشكلة ═══
-- ٨٦ إعلان صيدلاني بيظهروا في السوق باسم **«مضمونة»** — كسر مباشر
-- لقاعدة «مضمونة وسيط مش طرف». كلهم على حساب **الوصيّة**
-- (267e0655-96d9-431e-bf12-b4c2cd58778a) وهو حساب حجز مؤقت للإعلانات
-- اللي أصحابها لسه ماتسجلوش على المنصة.
--
-- ═══ ⛔ ليه ماعملتش حسابات موردين ═══
-- `marketplace_suppliers.profile_id` → `profiles.id` → **`auth.users.id`**.
-- يعني إنشاء مورد = **إنشاء حساب دخول** لشركة ماسجلتش عندنا. ده بالظبط
-- اللي عمل فوضى حسابات `agent-*` (قاعدة ٤.٨ — ١٤ مورد مكرر واتدمجوا)،
-- وكمان بيانات التواصل مش موجودة (٢٠ من ٢٦ شركة من غير رقم) — والاختراع
-- ممنوع. إنشاء حسابات لشركات حقيقية قرار مش بينفّذ من غير أمر صريح.
--
-- ═══ ✅ الحل ═══
-- عمود `listings.seller_display_name` — الاسم الحقيقي **بيتعرض**،
-- من غير حساب وهمي ومن غير اختراع بيانات.
--
-- مصدر الاسم: **عنوان الإعلان نفسه** (آخر مقطع بعد «—») — مش تخمين.
--   «APIs قلبية ومضادة للحساسية — Aastrid»            → Aastrid
--   «Pyrazinamide — أدوية السل (WHO) — Anuh Pharma»    → Anuh Pharma
--   «سواغ صيدلاني · Adchem»                            → Adchem (آخر «·»)
-- ⚠️ ملحوظة: أول محاولة أخدت **تاني** مقطع فطلّعت أوصاف منتجات
--    («قلب · مضادات عدوى · نفسية · أورام»). الصح هو **آخر** مقطع.
--
-- النتيجة: ٨٦ من ٨٦ اتربطوا · ٢٦ شركة حقيقية · صفر فاضل باسم مضمونة.
--
-- ═══ 📋 نطاق العمود ═══
-- **عرض فقط.** مش في الويزارد ولا المسودات — المورد اللي بيسجّل بنفسه
-- بياخد حساب وبيبان باسمه عادي. ده للإعلانات المحفوظة على حساب وصاية
-- لحد ما صاحبها يتسجّل، وساعتها الإعلان ينتقل لحسابه والعمود يتفضّى.
--
-- الكارت بيعرضه بأيقونة 🏭 **من غير لينك متجر** — لأن الشركة لسه
-- مالهاش متجر على المنصة، والينك الميت أسوأ من غيابه.
--
-- الرجوع: _backup_seller_display_20260902

alter table public.listings add column if not exists seller_display_name text;

comment on column public.listings.seller_display_name is
  'اسم البائع الحقيقي للعرض لما الإعلان محفوظ على حساب وصاية (٢/٩/٢٠٢٦). عرض فقط.';

