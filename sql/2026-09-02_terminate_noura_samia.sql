--
-- اتعرضت الخسائر الأول (قاعدة «قبل أي إجراء غير رجعي»)، ومحمد اختار
-- **إنهاء خدمة كامل** مش حذف نهائي. السبب: الموظف مربوط بـ٣٣ جدول، و
--   نورا  → ٤٥ إعلان شغّال + ١٠١ تاسكة + ١٦ يوم حضور + بند مرتب
--   سامية → ٥٤ تاسكة + ٩ حضور + بند مرتب
-- الحذف النهائي كان هيفصل الإعلانات عن اللي ضافها ويضرب حساب العمولة
-- والمرتب بأثر رجعي. الأثر بيتحفظ والوصول بيتقفل — نفس مبدأ ٤.٨.
--
-- ═══ الأبواب اللي اتقفلت مع بعض (قاعدة ٣: «بابين مش باب واحد») ═══
--   ١) business_employees.status = 'terminated'   ← هوية التطبيق
--   ٢) permissions = '{}'                          ← لو الحالة اتفتحت غلط
--   ٣) madmona_sessions اتلغت                      ← الجلسات المفتوحة
--   ٤) platform_admins اتشال                       ← باب لوحة /admin
--   ٥) crm_staff_settings: receives_leads=false و is_dispatcher=false
--
-- ═══ التحقق بعد التنفيذ ═══
--   الاتنين: status=terminated · permissions={} · صفر جلسة شغالة ·
--            صفر صف في platform_admins · صفر استقبال أرقام
--   المحفوظ: نورا ٤٥ إعلان + ١٠١ تاسكة · سامية ٥٤ تاسكة
--
-- ⚠️⚠️ **أثر تشغيلي مفتوح — محتاج قرار محمد:**
--   نورا كان معاها **٣٩٥ رقم CRM لسه شغّالين** (قطاعها: مطاعم + تجميل
--   حسب قاعدة التوزيع في CLAUDE.md ٤). دلوقتي الأرقام دي **مالهاش
--   مندوبة** — محدش هيكلّمهم. لازم يتحدد مين ياخد قطاع المطاعم والتجميل
--   وتتنقل ليه، وإلا ٣٩٥ ليد بتقف.
--   سامية كانت موزّعة (receives_leads=false) فمفيش أرقام عليها.
--
-- ═══ الرجوع ═══
--   _backup_terminated_20260902        (الصف بحالته وصلاحياته قبل الإنهاء)
--   _backup_terminated_admins_20260902 (صفوف platform_admins المتشالة)
--   كلهم RLS مفعّل وصفر صلاحية لـanon.

