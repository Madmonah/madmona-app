-- ═══ ٢) الإعلانات المستنية ═══
-- ٢٢ صف في `listing_drafts` طلعوا **٤ إعلانات حقيقية** بس — الباقي نسخ
-- حفظ تلقائي وصاحب الإعلان بيرفع الصور (صف لكل صورة).
--
--   ✅ «مدينتي» — استوديو ١٬٣٥٠٬٠٠٠ · ٨ صور → **اتنشر**
--   ⛔ «عربيه مستعمله» ٤٥٬٠٠٠ · ٤ صور → الترايجر رفض:
--      الرقم (+201099399899) مش موثّق بواتساب. **ده شغل القاعدة صح**
--      (قرار ٢٣ يوليو: التوثيق بالوارد بس) — بيتنشر أول ما صاحبه يبعت.
--   ⛔ «البحر الاحمر» — **بيانات غلط**: تصنيفه `sale-vehicles-used-car`
--      (عربية مستعملة) والمدينة شرم الشيخ والسعر ٤٠٠. محتاج مراجعة
--      بشرية مش نشر — نشره كده بيضر الثقة (قاعدة جودة الإعلان).
--   ⛔ «شقه في مصطفى النحاس» — رقمها رقم **عبير** (موظفة موقوفة)، وهي
--      **مكررة** مع إعلان موقوف أصلًا على حساب المنصة. محتاجة رقم
--      المالك الحقيقي.
