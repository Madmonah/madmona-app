--      **العروض الحقيقية** اللي بتتباع بالمتر — زي MT Mall (مول قائم،
--      وحدات تجارية، ٤ صور، تليفون، ومورد).
--
--      ✅ التفرقة الصح موجودة أصلًا جوّه الدالة: فلتر `unit_label` بيمسك
--         صفوف المؤشرات («سعر المتر» …). فسيبناه يشتغل، وشيلنا الاستبعاد
--         الشامل، **مع كتابة الوحدة في العنوان** — بنفس النمط المستخدم
--         مع `egp_night` و`egp_month` بالظبط:
--             «MT Mall — الحي الأول، 6 أكتوبر (سعر المتر)»
--         عشان محدش يقرا ٨٠ ألف على إنها تمن الوحدة.
