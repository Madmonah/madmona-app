insert into listing_photos (listing_id, url, is_primary)
select '0f3b09e5-a427-460c-be6a-483ec8f8c161', m.url, false
from (select value #>> '{}' as url
      from property_market_items pm,
           lateral jsonb_array_elements(pm.media) as t(value)
      where pm.id='485ef1cf-ea53-4775-ab25-8bf49c8c1a0e') m
where not exists (select 1 from listing_photos lp
                   where lp.listing_id='0f3b09e5-a427-460c-be6a-483ec8f8c161' and lp.url = m.url);
