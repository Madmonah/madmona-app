export async function POST(req: NextRequest) {
  try {
    const body = await req.json().catch(() => null) as
      | { imageBase64?: string; mimeType?: string }
      | null

    const b64 = (body?.imageBase64 || '').replace(/^data:[^;]+;base64,/, '')
    const mime = body?.mimeType || 'image/jpeg'

    if (!b64) {
      return NextResponse.json({ ok: false, error: 'مفيش صورة' }, { status: 400 })
    }
    // طول الـbase64 ÷ 4 × 3 ≈ حجم الملف الحقيقي
    if ((b64.length * 3) / 4 > MAX_BYTES) {
      return NextResponse.json(
        { ok: false, error: 'الصورة كبيرة أوي — جرّب صورة أصغر' },
        { status: 413 },
      )
    }
    if (!/^image\/(jpeg|png|webp|heic|heif)$/.test(mime)) {
      return NextResponse.json({ ok: false, error: 'نوع الصورة مش مدعوم' }, { status: 415 })
    }

    const raw = await callGemini({
      systemPrompt: SYSTEM_PROMPT,
      userMessage: 'صنّف الشغل اللي في الصورة دي.',
      images: [{ mimeType: mime, dataBase64: b64 }],
      maxTokens: 400,
      temperature: 0.2,
    })

    // الموديل بيلف الـJSON في ```json أحيانًا
    const jsonText = (raw.match(/\{[\s\S]*\}/) || [''])[0]
    let parsed: { job?: string; title?: string; reason?: string; confident?: boolean } = {}
    try { parsed = JSON.parse(jsonText) } catch { /* هنقع على الافتراضي تحت */ }

    // 🛡️ حارس: لو الموديل اخترع تايتل مش في القايمة، نرجّع "فرد"
    const title = TITLES.includes(parsed.title as typeof TITLES[number])
      ? (parsed.title as string)
      : 'فرد'

    return NextResponse.json({
      ok: true,
      title,
      // مفيش حالة «مش باين» — البرومبت بيلزمه بمهنة، ودي شبكة أمان بس
      job: (parsed.job || '').trim() || 'صاحب بيزنس',
      reason: parsed.reason || '',
      confident: parsed.confident !== false,
      system: SYSTEMS[title] || SYSTEMS['فرد'],
    })
  } catch (e) {
    const msg = e instanceof Error ? e.message : 'خطأ غير معروف'
    // الحد اليومي المجاني لجيميناي ١٥٠٠ نداء — الرسالة دي بتبان لو اتخطى
    const busy = /429|quota|exhaust/i.test(msg)
    return NextResponse.json(
      { ok: false, error: busy ? 'الخدمة مزنوقة شوية — جرّب كمان دقيقة' : 'مش قادرين نحلل الصورة دلوقتي' },
      { status: busy ? 429 : 500 },
    )
  }
}
