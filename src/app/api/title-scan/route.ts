  'من المطوّر': ['المشاريع والوحدات', 'الحجوزات', 'الربحية'],
  'متجر': ['الكتالوج والأسعار', 'الأوردرات', 'المخزون'],
  'مصنع': ['خطوط الإنتاج', 'الطلبات', 'العملاء'],
