  'سنتر': ['المجموعات والمواعيد', 'الطلاب', 'التحصيل'],
  'ورشة': ['الخدمات بأسعار', 'المواعيد', 'سجل العملاء'],
  'معرض عربيات': ['الكتالوج', 'الحجوزات', 'الاستيراد'],
