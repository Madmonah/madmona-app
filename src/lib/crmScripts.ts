/** 📄 الجزء اللي بيتضاف في آخر كل رسالة: النموذج + المطلوب + رقم الاستقبال.
 *
 *  (٢٣ أغسطس ٢٠٢٦ — محمد: «نموذج لكل معرض أو محل معمول بطريقة شيك، ونطلب
 *   من العميل يجهّز كل المطلوب ويبعت على واتساب ٠١٠٠٢٢٢٩٩٨٢»)
 *
 *  متجمّع في مكان واحد عن قصد: لو الرقم اتغيّر أو اتضاف نموذج جديد،
 *  بيتظبط هنا مرة واحدة وبيتحدّث في الاتناشر اسكريبت **وفي الورق
 *  المطبوع** في نفس اللحظة.
 */
/* 🗃️ (٢٤ أغسطس ٢٠٢٦ — محمد: «محتاج اعدل الرسالة وابعت معاها نموذج للتخصص»)
 *
 *  الاسكريبت والنموذج بقوا في جدول `crm_scripts` — يتعدّلوا من غير نشر.
 *  اللي تحت في الملف ده بقى **الافتراضي الآمن**: لو الجدول فاضي أو القراءة
 *  وقعت، الرسايل بتفضل زي ما هي بالحرف. أي عمود فاضي في الصف معناه
 *  «استخدم اللي في الكود» — فالتعديل الجزئي مسموح (مثلًا تغيّر النموذج بس).
 *
 *  الشاشة بتحمّلهم مرة واحدة مع القايمة وبتنادي `setScriptOverrides`.
 */
export type ScriptOverride = {
  specialty: string
  wa_body?: string | null
  demo_slug?: string | null
  demo_label?: string | null
  prepare_lines?: string[] | null
  intake_wa?: string | null
}
let OVERRIDES: Record<string, ScriptOverride> = {}
export function setScriptOverrides(rows: ScriptOverride[] | null | undefined) {
  if (!Array.isArray(rows) || !rows.length) return
  const next: Record<string, ScriptOverride> = {}
  for (const r of rows) if (r?.specialty) next[r.specialty] = r
  OVERRIDES = next
}

function tailFor(key: string) {
  const ov = OVERRIDES[key]
  const demoSlug = ov?.demo_slug ?? DEMOS[key]?.slug ?? null
  const demoLabel = ov?.demo_label ?? DEMOS[key]?.label ?? null
  const prep = (ov?.prepare_lines?.length ? ov.prepare_lines : null) || PREPARE[key] || PREPARE.other
  const intake = ov?.intake_wa || INTAKE_WA
  const lines: string[] = []

  if (demoSlug) {
    lines.push(`شوف نموذج حقيقي شغّال عندنا${demoLabel ? ` — ${demoLabel}` : ''}:`)
    lines.push(`https://madmonacairo.com/s/${demoSlug}`)
  } else {
    // مفيش نموذج للنشاط ده لسه — مابنبعتش لينك مالوش لازمة
    lines.push('أبعتلك نموذج تشوفه بعينك قبل ما تقرر.')
  }

  lines.push('')
  lines.push('عشان نجهّزلك صفحتك، محتاجين منك:')
  prep.forEach((p) => lines.push(`• ${p}`))
  lines.push('')
  lines.push(`ابعتهم واتساب على ${intake} وإحنا نظبّطها ونبعتهالك جاهزة.`)

  return lines.join('\n')
}

/** نص الرسالة كامل — الافتتاحية + النموذج + المطلوب + رقم الاستقبال. */
export function scriptText(specialty: string | null, customer: string | null, sender: string | null) {
  const key = CRM_SCRIPTS[specialty || ''] ? (specialty as string) : 'other'
  const ov = OVERRIDES[key]
  /* النص المعدّل من الشاشة بيدعم نفس المتغيرين اللي في الكود: {customer} {sender} */
  const opener = ov?.wa_body?.trim()
    ? ov.wa_body
        .replace(/\{customer\}/g, customer || 'حضرتك')
        .replace(/\{sender\}/g, sender ? `${sender} من مضمونة` : 'فريق مضمونة')
        .trimEnd()
    : scriptFor(specialty).wa(customer, sender).trimEnd()
  return `${opener}\n\n${tailFor(key)}`
}

/** الرقم بالصيغة الدولية اللي واتساب بيفهمها (201XXXXXXXXX). */
export function waIntl(phone: string) {
  const d = (phone || '').replace(/\D/g, '')
  if (!d) return ''
  if (d.startsWith('20')) return d
  if (d.startsWith('0')) return `2${d}`
  if (d.startsWith('1') && d.length === 10) return `20${d}`
  return d
}

/** لينك واتساب جاهز بالرسالة — بيفتح المحادثة والرسالة مكتوبة.
 *
 *  🐞 (٢٣ أغسطس ٢٠٢٦ — محمد: «لسة زرار واتساب بيفتح الرسالة فاضية»)
 *     كنا بنستخدم `wa.me/<رقم>?text=…`. اتأكدنا إن اللينك بيتولّد صح وإن
 *     النص موجود في النسخة المرفوعة فعلاً — يعني المشكلة مش عندنا في
 *     التوليد، دي في اللي بيفتح اللينك: `wa.me` بيرمي الـ`text` في حالات
 *     كتير (خصوصًا لما ويندوز/أندرويد يسلّم اللينك لتطبيق واتساب المثبّت
 *     بدل المتصفح).
 *
 *     `api.whatsapp.com/send` هو الشكل الرسمي المكتوب في دوكس واتساب
 *     للـclick-to-chat وبيحافظ على النص أحسن. وفوق ده بننسخ الرسالة
 *     للكليبورد في نفس الضغطة (شوف الزرار في src/app/crm/page.tsx) —
 *     فحتى لو التطبيق رماها، الموظف بيلزق بضغطة واحدة.
 */
export function waLink(phone: string, specialty: string | null, customer: string | null, sender: string | null) {
  return `https://api.whatsapp.com/send?phone=${waIntl(phone)}&text=${encodeURIComponent(scriptText(specialty, customer, sender))}`
}

/** 📱 (٢٣ أغسطس ٢٠٢٦ — محمد: «عايز تاب إرسال الواتساب تخيّرهم بين واتساب
 *  بيزنس أو واتساب عادي»)
 *
 *  التطبيقين على أندرويد بيتسجّلوا على **نفس الـscheme** (whatsapp://)،
 *  فأي لينك عادي بيفتح أي واحد فيهم على كيف النظام. صيغة intent:// بـ
 *  package صريح هي الوحيدة اللي بتحدّد تطبيق بعينه:
 *      العادي = com.whatsapp · البيزنس = com.whatsapp.w4b
 *
 *  S.browser_fallback_url: لو التطبيق ده مش متسطّب، كروم بيرجع للينك
 *  العادي بدل ما يقف على صفحة خطأ.
 *
 *  ⚠️ على iOS والديسكتوب مفيش scheme منفصل لواتساب بيزنس — فالواجهة
 *     بتعرض زرار واحد هناك بدل زرارين بيعملوا نفس الحاجة بالظبط.
 */
export type WaApp = 'normal' | 'business'

export function waAppLink(
  app: WaApp,
  phone: string,
  specialty: string | null,
  customer: string | null,
  sender: string | null,
) {
  const pkg = app === 'business' ? 'com.whatsapp.w4b' : 'com.whatsapp'
  const text = encodeURIComponent(scriptText(specialty, customer, sender))
  const fallback = encodeURIComponent(waLink(phone, specialty, customer, sender))
  return `intent://send?phone=${waIntl(phone)}&text=${text}`
    + `#Intent;scheme=whatsapp;package=${pkg};S.browser_fallback_url=${fallback};end`
}

/** أندرويد بس هو اللي بيقدر يحدّد تطبيق بعينه. */
export function canPickWaApp() {
  return typeof navigator !== 'undefined' && /Android/i.test(navigator.userAgent)
}
