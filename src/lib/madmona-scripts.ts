/** بيختار العرض المناسب من نوع النشاط. */
export function cloudPitchFor(kind: string | null | undefined): string {
  const k = (kind || '').toLowerCase()
  if (/car|vehicle|عرب|سيار|توكيل|معرض/.test(k)) return PITCH_CLOUD_SHOWROOM
  if (/clinic|polyclinic|عياد|دكتور|طبيب|أسنان/.test(k)) return PITCH_CLOUD_CLINIC
  if (/shop|store|retail|market|pharmac|محل|متجر|صيدل|سوبر|بوتيك/.test(k)) return PITCH_CLOUD_STORE
  return PITCH_CLOUD_GENERIC
}

