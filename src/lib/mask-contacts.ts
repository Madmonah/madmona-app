// 🔒 (٢٧ أغسطس ٢٠٢٦) محمد: «مش هنعرض الاسم ورقم التليفون إلا لما يتم الاتفاق
//     في حضور مضمونة».
//
// إخفاء الأسماء في واجهة الشات مش كفاية: أي طرف يقدر يكتب رقمه **في نص
// الرسالة** والرقم يوصل للطرف التاني عادي، والصفقة تتقفل بره المنصة.
// الملف ده بيمسك أرقام التليفون والإيميلات ومعرّفات السوشيال جوّه نص
// الرسالة في الرومات المخفية، ويحطّ مكانها علامة واضحة.
//
// ⚠️ ده حاجز، مش قفل محكم — حد مصمّم يقدر يكتب رقمه بالحروف («صفر واحد
//    اتنين…»). الهدف منع التسريب العادي، وإن الطرفين يفهموا إن ده مش
//    المكان المناسب. الفريق شايف الرسالة الأصلية في روم المتابعة.
// ============================================================================

/** رقم موبايل مصري: 01xxxxxxxxx أو +201xxxxxxxxx أو بمسافات/شرط بينهم */
const EG_PHONE = /(?:\+?2\s*0?)?1\s*[0125](?:[\s\-.]?\d){8}/g
/** أي سلسلة ٩ أرقام أو أكتر (أرقام أرضي ودولية) */
const LONG_DIGITS = /\d(?:[\s\-.]?\d){8,}/g
/** أرقام عربية-هندية (٠١٢٣…) — الناس بتكتب بيها كتير */
const AR_DIGITS = /[\u0660-\u0669](?:[\s\-.]?[\u0660-\u0669]){8,}/g
const EMAIL = /[\w.+-]+@[\w-]+\.[\w.]{2,}/g
/** يوزرات السوشيال + لينكات التواصل المباشر */
const HANDLES = /(?:wa\.me\/|t\.me\/|m\.me\/|instagram\.com\/|facebook\.com\/|@[A-Za-z_][\w.]{2,})\S*/g

export const MASK_TOKEN = '••••••'

/** بيرجّع true لو النص فيه وسيلة تواصل مباشرة */
export function hasContactInfo(text: string): boolean {
  if (!text) return false
  return [EG_PHONE, LONG_DIGITS, AR_DIGITS, EMAIL, HANDLES].some((re) => {
    re.lastIndex = 0
    return re.test(text)
  })
}

/** بيشيل وسائل التواصل من النص ويحطّ مكانها MASK_TOKEN */
export function maskContacts(text: string): string {
  if (!text) return text
  let out = text
  for (const re of [EG_PHONE, AR_DIGITS, LONG_DIGITS, EMAIL, HANDLES]) {
    out = out.replace(re, MASK_TOKEN)
  }
  return out
}

/** رسالة التنبيه اللي بتتعرض تحت الرسالة المتخفية */
export const MASK_NOTICE = '🔒 اتخفى رقم/وسيلة تواصل — التواصل بيتم من خلال مضمونة لحد ما يتم الاتفاق.'
