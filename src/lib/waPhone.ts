// 📱 تطبيع رقم الواتساب للينكات wa.me
//
// (١٨ أغسطس ٢٠٢٦ — محمد: «بفتح ابعت واتساب بيجيبلي صفحة الليد») —
// زراير الواتساب في لوحة الأدمن كانت بتحط الرقم زي ما هو في wa.me/…،
// والأرقام المتسجلة بالصيغة المحلية (01xxxxxxxxx من غير كود مصر) واتساب
// مش بيعرفها — فبدل ما يفتح الشات بيفتح صفحة ويب. الدالة دي بتطبّع أي
// صيغة لرقم دولي صحيح:
//   «01012345678»   → «201012345678»
//   «+201012345678» → «201012345678»
//   «1012345678»    → «201012345678»
//   «201012345678»  → زي ما هو
// ============================================================================
export function waPhone(p?: string | null): string {
  const d = (p || '').replace(/\D/g, '')
  if (!d) return ''
  if (d.startsWith('20')) return d
  if (d.startsWith('0')) return '2' + d
  if (d.startsWith('1') && d.length === 10) return '20' + d
  return d
}
